def build(base_rows):
    rows = []
    for r in base_rows:
        gold = json.loads(r["gold"])
        base_hits = {k: v["noul"] >= 0.5 for k, v in gold.items() if k in ("jailbreak", "prompt_injection", "sensitive_data", "abuse")}
        rows.append(make_row(r["id"], json.loads(r["state"]), base_hits))
    k = 0
    for t in CRISIS:
        rows.append(make_row(f"v13_crisis_{k:03d}", t, {"crisis": True})); k += 1
    for t in BULLYING:
        rows.append(make_row(f"v13_bully_{k:03d}", t, {"bullying": True})); k += 1
    for t in NORMAL:
        rows.append(make_row(f"v13_normal_{k:03d}", t, {})); k += 1
    return rows


