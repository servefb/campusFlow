"""submit_answer：最终回答的**唯一**出口（结构性解决"过程/回答混流"问题）。

背景：agent 的中间独白和给用户的回答走同一条消息流，靠"有没有工具调用、
是不是最后一条"去猜，猜错就出现"工具输出闪现在回答区"这类问题。
把回答做成一次工具调用后，分类变成确定性的：
    · 一切普通文本 = 工作过程（进「工作过程」面板，永不进正文区）；
    · submit_answer 的 answer 参数 = 给用户的回答（流式到达，真打字机）。

return_direct=True 是框架原生的收尾机制（langchain agents factory 的 exit_node）：
模型调用本工具后 agent 循环立即结束，不会继续自言自语。
"""
from langchain_core.tools import tool


@tool(return_direct=True)
def submit_answer(answer: str) -> str:
    """把最终回答提交给用户。这是回答到达用户的**唯一**通道：不调用本工具，用户什么也看不到。

    使用规则：
    - answer 必须是**面向用户的完整回答**（可以直接发送，不需要再加工）；
    - 调用前的所有文字（打算做什么、分析过程）都会进入「工作过程」面板，
      不会展示给用户——不要在那里写给用户的内容，也不要复述工具返回的原文；
    - 本工具单独调用，不要与其他工具在同一条消息里一起调用；
    - 需要继续调用其他工具时，先不要调用本工具。
    """
    return answer
