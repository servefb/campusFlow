# ── 与 doc_v12 旧数据 + 全部评测集（含旧 doc 评测）做精确 + 相似度双重校验 ──
import glob
guard_states = set()
for fn in ["_finetune_train_doc_v12.jsonl", "_finetune_train_doc_desktop.jsonl"] + \
           sorted(glob.glob("_finetune_eval_*.jsonl")) + \
           sorted(glob.glob("_finetune_train_input_v1*.jsonl")):
    try:
        for l in open(fn, encoding="utf-8"):
            if not l.strip():
                continue
            r = json.loads(l)
            guard_states.add(r.get("state") or json.dumps(r.get("text", ""), ensure_ascii=False))
    except FileNotFoundError:
        pass

SIM_THRESHOLD = 0.6
exact, similar = [], []
for r in rows:
    if not r["id"].startswith("v13doc_"):
        continue
    if r["state"] in guard_states:
        exact.append(r["id"])
        continue
    best = max((SequenceMatcher(None, r["state"], ts).ratio() for ts in guard_states), default=0.0)
    if best >= SIM_THRESHOLD:
        similar.append((r["id"], round(best, 3), json.loads(r["state"])[:30]))

if exact or similar:
    print("EXACT DUP:", exact)
    for s in similar:
        print("SIMILAR:", s)
    raise SystemExit("存在与历史训练/评测重复的样本，请改写后再生成")

